-- v0.0.86: 아티팩트 주제별 폴더 (한 단계, 아티팩트는 한 폴더에만). folder_id NULL = 미분류.
CREATE TABLE artifact_folders (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(50) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- 대소문자 무시 중복 금지 ("설계" / "Design" 과 "design" 공존 방지)
CREATE UNIQUE INDEX uq_artifact_folders_name ON artifact_folders (lower(name));

-- ON DELETE SET NULL: 폴더를 지우면 DB 가 안의 아티팩트를 자동으로 미분류로 돌린다.
ALTER TABLE artifacts ADD COLUMN folder_id BIGINT REFERENCES artifact_folders (id) ON DELETE SET NULL;
CREATE INDEX idx_artifacts_folder ON artifacts (folder_id);
