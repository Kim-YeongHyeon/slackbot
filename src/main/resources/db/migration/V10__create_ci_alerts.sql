-- #sol-sbom-ci 알림 자동 대응 (v0.0.91). 알림 1건 = 1행.
-- (channel, message_ts) 유니크 — Slack 이벤트 재전송·서버 재시작에도 같은 알림을 두 번 처리하지 않는다.
-- fingerprint 는 반복 알림(같은 원인) 판단용, vuln_ids·pr_urls 는 SBOM 자동 수정(v0.0.92~)용.
CREATE TABLE ci_alerts (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel      VARCHAR(40)  NOT NULL,
    message_ts   VARCHAR(40)  NOT NULL,
    repo         VARCHAR(100),
    run_id       BIGINT,
    kind         VARCHAR(20),
    status       VARCHAR(20)  NOT NULL,
    fingerprint  VARCHAR(64),
    category     VARCHAR(20),
    summary      TEXT,
    reply_ts     VARCHAR(40),
    vuln_ids     TEXT,
    pr_urls      TEXT,
    error        TEXT,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_ci_alerts_message UNIQUE (channel, message_ts)
);

CREATE INDEX idx_ci_alerts_repeat ON ci_alerts (repo, fingerprint, created_at);
